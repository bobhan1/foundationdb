#!/usr/bin/env bash

set -euo pipefail

usage() {
	cat <<'EOF'
Usage:
  build_fdb_upgrade_bundle.sh --version VERSION [options]

Downloads FoundationDB release binaries on a machine with good internet access,
verifies the upstream sha256 files, and packs them into a single bundle tar.gz.

Options:
  --version VERSION            Primary version to package. Required.
  --arch ARCH                  x86_64 or aarch64. Default: x86_64
  --curl-bin PATH              Curl binary to use. Default: curl
  --release-base URL           Default: https://github.com/apple/foundationdb/releases/download
  --work-dir PATH              Temp/cache dir. Default: ./fdb-bundle-work
  --output PATH                Output tar.gz path. Default: ./fdb-upgrade-bundle-<version>.tar.gz
  -h, --help                   Show help

The bundle contains:
  - manifest.env
  - packages/<version>/fdbserver.<arch>
  - packages/<version>/fdbcli.<arch>
  - packages/<version>/fdbbackup.<arch>
  - matching .sha256 files
EOF
}

log() {
	printf '[%s] %s\n' "$(date '+%F %T')" "$*" >&2
}

die() {
	log "ERROR: $*"
	exit 1
}

VERSION=''
ARCH='x86_64'
CURL_BIN='curl'
RELEASE_BASE='https://github.com/apple/foundationdb/releases/download'
WORK_DIR='./fdb-bundle-work'
OUTPUT=''

while (($#)); do
	case "$1" in
		--version)
			shift
			VERSION=${1:?missing value for --version}
			;;
		--arch)
			shift
			ARCH=${1:?missing value for --arch}
			;;
		--curl-bin)
			shift
			CURL_BIN=${1:?missing value for --curl-bin}
			;;
		--release-base)
			shift
			RELEASE_BASE=${1:?missing value for --release-base}
			;;
		--work-dir)
			shift
			WORK_DIR=${1:?missing value for --work-dir}
			;;
		--output)
			shift
			OUTPUT=${1:?missing value for --output}
			;;
		-h|--help)
			usage
			exit 0
			;;
		*)
			die "unknown argument: $1"
			;;
	esac
	shift
done

[[ -n ${VERSION} ]] || die "--version is required"

case "${ARCH}" in
	x86_64|aarch64) ;;
	*)
		die "--arch must be x86_64 or aarch64"
		;;
esac

if [[ ${CURL_BIN} != */* ]]; then
	command -v "${CURL_BIN}" >/dev/null 2>&1 || die "curl binary not found: ${CURL_BIN}"
else
	[[ -x ${CURL_BIN} ]] || die "curl binary is not executable: ${CURL_BIN}"
fi
command -v sha256sum >/dev/null 2>&1 || die "sha256sum is required"
command -v tar >/dev/null 2>&1 || die "tar is required"

OUTPUT=${OUTPUT:-./fdb-upgrade-bundle-${VERSION}-${ARCH}.tar.gz}

ASSETS=(
	"fdbserver.${ARCH}"
	"fdbcli.${ARCH}"
	"fdbbackup.${ARCH}"
)

download_one_version() {
	local version=$1
	local version_dir="${WORK_DIR}/packages/${version}"

	mkdir -p "${version_dir}"
	for asset in "${ASSETS[@]}"; do
		local base_url="${RELEASE_BASE}/${version}/${asset}"
		log "downloading ${asset} for ${version}"
		"${CURL_BIN}" -fsSL -o "${version_dir}/${asset}" "${base_url}"
		"${CURL_BIN}" -fsSL -o "${version_dir}/${asset}.sha256" "${base_url}.sha256"
		(
			cd "${version_dir}"
			sha256sum -c "${asset}.sha256"
		)
		chmod 0755 "${version_dir}/${asset}"
	done
}

rm -rf "${WORK_DIR}"
mkdir -p "${WORK_DIR}/packages"

download_one_version "${VERSION}"

cat > "${WORK_DIR}/manifest.env" <<EOF
PRIMARY_VERSION='${VERSION}'
ARCH='${ARCH}'
ASSETS='${ASSETS[*]}'
BUILT_AT='$(date -u '+%Y-%m-%dT%H:%M:%SZ')'
EOF

cat > "${WORK_DIR}/README.txt" <<EOF
This bundle was generated by build_fdb_upgrade_bundle.sh.

Use apply_fdb_upgrade_bundle.sh to:
1. distribute the bundle to all hosts
2. unpack the bundle on each host
3. switch symlinks to the staged version
4. run the currently running version's fdbcli with "kill; kill all"
5. wait for fdbmonitor to restart the target fdbserver version
6. switch the fdbcli symlink after the server version change is confirmed
EOF

tar -C "${WORK_DIR}" -czf "${OUTPUT}" manifest.env README.txt packages
sha256sum "${OUTPUT}" > "${OUTPUT}.sha256"

log "bundle created: ${OUTPUT}"
log "bundle checksum: ${OUTPUT}.sha256"
